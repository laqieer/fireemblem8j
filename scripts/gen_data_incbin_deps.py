#!/usr/bin/env python3
"""Generate Make dependencies: each src/data/**/*.c object depends on the assets
it INCBINs, so a CLEAN parallel build generates the (gitignored) graphics/sound
.4bpp/.lz/.bin assets BEFORE the object is compiled.

Without this, `src/data/<sub>/X.o` (DATA_INCBIN_OBJECTS) compiles `.incbin
"graphics/Y.4bpp"` before gbagfx has produced Y.4bpp from the committed Y.png ->
CI (clean checkout) fails even though a local tree (assets already present) passes.

Writes layout/data_incbin_deps.mk (tracked, -included by the Makefile).
"""
import re, glob, os

# A multi-path INCBIN_U8("a","b",off,len,"c") concatenates SEVERAL assets -- every
# quoted path is a build dependency, not just the first. Match the whole arg list,
# then pull out all quoted paths (numeric slice args are ignored).
INCBIN = re.compile(r'INCBIN_(?:U8|U16|U32)\(([^)]*)\)')
def incbin_assets(text):
    out = []
    for args in INCBIN.findall(text):
        out += re.findall(r'"([^"]+)"', args)
    return out

lines = ["# AUTO-GENERATED by scripts/gen_data_incbin_deps.py -- do not edit by hand.",
         "# Each src/data/**/*.o depends on the assets its .c INCBINs (clean-build ordering).", ""]
cfiles = [f for f in glob.glob('src/data/**/*.c', recursive=True)
          if '/map/' not in f and f.count('/') >= 3]   # depth>=2 = DATA_INCBIN_CFILES
n = 0
for c in sorted(cfiles):
    assets = sorted(set(incbin_assets(open(c, errors='replace').read())))
    if not assets:
        continue
    obj = c[:-2] + '.o'
    lines.append(f"{obj}: {' '.join(assets)}")
    n += 1
open('layout/data_incbin_deps.mk', 'w').write('\n'.join(lines) + '\n')
print(f"wrote layout/data_incbin_deps.mk: {n} objects with asset deps")
