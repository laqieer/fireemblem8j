#!/usr/bin/env python3
"""Generate shared-oracle stub declarations for sub_8057F80 spike.

This intentionally lives beside the focused harness so future attempts can extend it.
It scans the reconstruction and m2c reference for apparent function calls, filters C
keywords/control constructs, and emits call-indexed oracle skeletons.  The current
stop-loss spike records this generated inventory in oracle_stubs.generated.h; a fully
closing proof still needs hand/classification of pointer-write side effects per callee.
"""
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[7]
IMPL = ROOT / "src/nonmatching/sub_8057F80.c"
REF = ROOT / "scripts/tools/thumb_equiv/cbmc_spike/full16/generated/reference_c/sub_8057F80_ref.c"
OUT = Path(__file__).with_name("oracle_stubs.generated.h")
SKIP = {"if", "for", "while", "switch", "return", "sizeof", "ABS", "M2C_FIELD"}

def calls(path):
    text = path.read_text()
    text = re.sub(r"/\*.*?\*/", "", text, flags=re.S)
    text = re.sub(r"//.*", "", text)
    return set(m.group(1) for m in re.finditer(r"\b([A-Za-z_]\w*)\s*\(", text) if m.group(1) not in SKIP)

names = sorted((calls(IMPL) | calls(REF)) - {"PrepareBattleGraphicsMaybe", "GetBanimAllyPositionJ"})
with OUT.open("w") as f:
    f.write("/* Auto-generated by gen_shared_oracles.py.  Inventory only. */\n")
    f.write("#ifndef SUB_8057F80_ORACLE_STUBS_GENERATED_H\n#define SUB_8057F80_ORACLE_STUBS_GENERATED_H\n\n")
    f.write(f"#define SUB_8057F80_ORACLE_COUNT {len(names)}\n")
    f.write("static const char *const g_sub_8057F80_oracle_names[] = {\n")
    for n in names:
        f.write(f"    \"{n}\",\n")
    f.write("};\n\n")
    for idx, n in enumerate(names):
        f.write(f"/* {idx:03d}: {n} -- generate a ref-record/impl-assert shared oracle stub here. */\n")
    f.write("\n#endif\n")
print(f"wrote {OUT} with {len(names)} callees")
