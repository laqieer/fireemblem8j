//! FE8U = 0x0800FCD8
u32 ModifyMoveUnitFlag(struct EventEngineProc * proc, s8 unk)
{
    u16 result;

    // TODO: use some enum constants

    if (unk == TRUE)
        result = 1;
    else
        result = 0;

    if (proc->evStateBits & EV_STATE_UNITCAM)
        result = result | 4;

    if (proc->evStateBits & EV_STATE_0040)
        result = result | 8;

    return result;
}
